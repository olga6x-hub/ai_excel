        ["2", "По ходу", "Студент отмечает старт и финиш блока (сообщением), менеджер переносит в «Блоки». "
                         "Стоп — если на одном шаге просидел больше 10 минут."],
        ["3", "После блока", "Анкета из `anketa-pilota.docx` (6 вопросов). Баллы квизов — в лист «Квизы»."],
        ["4", "День 13", "Сводка заполняется формулами автоматически. Дописать цитаты из анкет без редактуры."],
        ["5", "Итог", "Список правок P0/P1/P2 + решение по C-2, порогу завершения урока и проверке портфеля."],
