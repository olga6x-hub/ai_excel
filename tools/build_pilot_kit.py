    ws["A1"] = "Сводка пилота"
    ws["A1"].font = Font(bold=True, size=14, name="Segoe UI")
    rows = [
        ("Участников", "=COUNTA(Студенты!B3:B12)-COUNTBLANK(Студенты!B3:B12)", "цель 3–5"),
        ("Прошли проверку платформы", '=COUNTIF(Студенты!D3:D12,"да")', "цель все"),
        ("Дошли до урока 6 и дальше", '=COUNTIF(Студенты!G3:G12,">=6")', "цель ≥ 80 %"),
        ("Среднее минут на блок", "=IFERROR(AVERAGE(Блоки!E2:E29),0)", "цель ≤ 90"),
        ("Максимум минут на блок", "=IFERROR(MAX(Блоки!E2:E29),0)", "смотрим выбросы"),
        ("Стопов всего", "=IFERROR(SUM(Блоки!F2:F29),0)", "цель ≤ 2 на урок"),
        ("Технических сбоев", '=COUNTIF(Блоки!H2:H29,"да")', "≤ 2 на студента"),
        ("Средний балл квизов", "=IFERROR(AVERAGE(Квизы!C2:C19),0)", "цель 70–85 %"),
        ("Квизов со 100 %", '=COUNTIF(Квизы!C2:C19,100)', "0 — хорошо"),
    ]
    ws.append([])
    ws.append(["Показатель", "Значение", "Ориентир"])
    for cell in ws[3]:
        cell.font, cell.fill, cell.border, cell.alignment = HDR_FONT, HDR_FILL, BORDER, CENTER
    r = 4
    for name, formula, target in rows:
        ws.cell(row=r, column=1, value=name).font = BODY
        ws.cell(row=r, column=2, value=formula).font = BODY
        ws.cell(row=r, column=3, value=target).font = BODY
        for j in (1, 2, 3):
            ws.cell(row=r, column=j).border = BORDER
            ws.cell(row=r, column=j).alignment = WRAP
        r += 1
    ws.column_dimensions["A"].width = 32
    ws.column_dimensions["B"].width = 16
