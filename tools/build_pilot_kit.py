          ["Студент", "Блок", "Дата старта", "Дата финиша", "Минут на блок",
           "Стопов (>10 мин)", "Обращений в поддержку", "Технический сбой (да/нет)",
           "Где застрял (шаг)", "Комментарий"],
          [[f"S{i}", b, "", "", "", "", "", "", "", ""] for i in (1, 2, 3) for b in range(1, 7)],
          [9, 7, 12, 12, 14, 14, 16, 16, 28, 30],
