#!/usr/bin/env python3
"""Пилотный комплект курса «ai-excel»: план, анкета, трекер метрик.

Создаёт `courses/ai-excel/pilot/`:
  plan-pilota.md        — протокол: цель, участники, расписание, метрики, go/no-go, роли
  anketa-pilota.docx    — анкета после блока (6 вопросов) + финальная (цена, NPS)
  tracker-pilota.xlsx   — трекер: студенты, блоки, квизы, сводка, инструкция
  README.md             — что с чем и в каком порядке

Запуск из корня harness: python tools/build_pilot_kit.py
"""
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "courses" / "ai-excel" / "pilot"

ORANGE = "D97757"
th = Side(style="thin", color="E4E4E4")
BORDER = Border(left=th, right=th, top=th, bottom=th)
HDR_FONT = Font(bold=True, color="FFFFFF", size=10, name="Segoe UI")
HDR_FILL = PatternFill("solid", fgColor=ORANGE)
BODY = Font(size=10, name="Segoe UI")
WRAP = Alignment(wrap_text=True, vertical="top")
CENTER = Alignment(horizontal="center", vertical="center", wrap_text=True)

PLAN = """# План пилота курса «Табличный редактор текстом»

Пилот отвечает на три вопроса: **посильно ли** (время и нагрузка), **понятно ли** (без преподавателя),
**работает ли техника** (платформа + Moodle). Всё остальное — вторично.

## 1. Участники

3–5 человек. Критерии отбора:

- есть компьютер (не только телефон) и агентская платформа, прошедшая предстартовую проверку
  из нулевого раздела;
- умеет открыть файл, отфильтровать, посмотреть сумму — не новичок «с нуля»;
- готов потратить 8–9 часов за две недели и сдать портфель;
- согласен на запись экрана или логи диалога с агентом (по желанию — без них тоже можно).

Если платформу не прошёл — не берём или переносим на следующий поток. Это не отбор «сильных»,
это защита пилота от технического шума.

## 2. Расписание (12 дней)

| День | Что происходит | Кто |
|---|---|---|
| 0 | Онбординг 20 минут: нулевой раздел, свой вариант датасета, рабочая папка, предстартовая проверка | Менеджер |
| 1–3 | Блок 1 + блок 2 (уроки 1–2) | Студент |
| 3 | Созвон 20 минут: как прошла чистка данных, где застряли | Ольга/менеджер |
| 4–5 | Блок 3 (уроки 3–4) | Студент |
| 6–8 | Блок 4 (уроки 5–6) | Студент |
| 9–10 | Блок 5 (уроки 7–8) | Студент |
| 11–12 | Блок 6 (урок 9) + финальная анкета | Студент |

Ритм мягкий: если человек отстаёт на день — не страшно, важна последовательность, а не даты.

## 3. Роли

- **Ольга** — владелец пилота: решения по ходу, оценка результатов, что меняем в курсе.
- **Менеджер Moodle** — сборка курса, доступы, техподдержка первой линии.
- **Агент (Hermes)** — обработка данных трекера, список правок по итогам, пересборка материалов.

## 4. Метрики

Заполняется в `tracker-pilota.xlsx` по каждому студенту и каждому блоку.

| Метрика | Как снимаем | Целевое значение |
|---|---|---|
| Время на блок | дата/время старта и финиша в трекере | ≤ 90 мин на блок |
| Доходимость | число пройденных уроков и квизов | ≥ 80 % доходят до урока 6 |
| Где застревают | отметка «стоп» (>10 минут на одном шаге) | ≤ 2 стопов на урок |
| Технические сбои | отдельная колонка в трекере | ≤ 2 на студента |
| Результат квизов | баллы и число попыток из Moodle | средний 70–85 %, не 100 % |
| Понятность без преподавателя | анкета, шкала 1–5 | ≥ 4 по «понятно, что делать» |
| Готовность рекомендовать | финальная анкета, 0–10 | ≥ 8 |

## 5. Критерии go / no-go

**Идём в продажи, если:** ≥ 80 % дошли до урока 6, медианное время ≤ 90 мин на блок, ≥ 4/5 по
понятности, ни одного блокирующего техдефекта, квизы не дают 100 % (иначе вопросы слишком лёгкие).

**Возвращаемся на правку, если:** больше трети отвалились, среднее время блока > 2 часов,
или на квизах массово 90–100 % (значит, проверяем не то).

**Стоп-сигнал:** больше половины сбоев — технические (платформа), а не методические. Тогда первым
делом решается среда практики, а не контент.

## 6. Что делаем с результатами

1. Сводка по метрикам + список цитат из анкет (без редактуры).
2. Список правок: P0 (ломает прохождение), P1 (мешает), P2 (косметика) — с оценкой времени.
3. Решение по трём открытым пунктам: среда практики для продаж (C-2), порог завершения урока
   (аудио 95 % или «просмотрено»), кто проверяет портфель.
4. Только после этого — цена и лендинг (правило ворот Gecko: цена не назначается до тест-группы).

## 7. Риски и запасные планы

| Риск | Что делаем |
|---|---|
| Платформа студента не тянет агентский режим | замена платформы или перенос на следующий поток; фиксируем как данные для C-2 |
| Отваливаются 2 из 5 | добираем 2 человека из листа ожидания, пилот не продлеваем |
| Урок не закрывается (аудио не прослушано) | менеджер закрывает вручную, случай фиксируем в трекере как дефект P1 |
| Кто-то не сдаёт портфель | считаем как результат (доходимость), не как «выпал» |
| Пилот растягивается | жёсткий дедлайн 14 дней, дальше собираем что есть |

## 8. Что нужно подготовить до дня 0

- [ ] Курс собран в Moodle, группы вариантов, квизы, пороги
- [ ] Прогон ролью `student` по варианту A
- [ ] Нулевой раздел опубликован (`start/index.html`)
- [ ] Выданы датасеты и шаблоны
- [ ] Трекер заведён, анкета разослана
- [ ] Определено, кто отвечает на вопросы в рабочие часы и в какие
"""

README = """# Пилотный комплект

| Файл | Что это |
|---|---|
| `plan-pilota.md` | протокол пилота: участники, расписание, метрики, критерии go/no-go, роли |
| `anketa-pilota.docx` | анкета после каждого блока (6 вопросов) и финальная (цена, рекомендация) |
| `tracker-pilota.xlsx` | трекер: студенты, блоки (время, стопы, сбои), квизы, сводка, инструкция |

Порядок: прочитать план → завести трекер по числу студентов → разослать анкету после блока 1 →
собирать данные по ходу → свести на 13-й день → список правок.

Анкета заполняется после каждого блока (6 раз) и один раз в конце. Если это тяжело — минимум
блок 2 и блок 9: на них видно и допуск, и итог.
"""


def sheet(wb, title, header, rows, widths, extra=6, note=None):
    ws = wb.create_sheet(title)
    r = 1
    if note:
        c = ws.cell(row=1, column=1, value=note)
        c.font = Font(italic=True, size=9, color="6B6B6B", name="Segoe UI")
        c.alignment = WRAP
        ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=len(header))
        ws.row_dimensions[1].height = 28
        r = 2
    for j, h in enumerate(header, 1):
        c = ws.cell(row=r, column=j, value=h)
        c.font, c.fill, c.border, c.alignment = HDR_FONT, HDR_FILL, BORDER, CENTER
    ws.row_dimensions[r].height = 32
    for i, row in enumerate(rows, r + 1):
        for j, v in enumerate(row, 1):
            c = ws.cell(row=i, column=j, value=v)
            c.font, c.border, c.alignment = BODY, BORDER, WRAP
    last = r + len(rows) + extra
    for i in range(r + len(rows) + 1, last + 1):
        for j in range(1, len(header) + 1):
            c = ws.cell(row=i, column=j)
            c.border, c.alignment = BORDER, WRAP
    for j, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(j)].width = w
    ws.freeze_panes = "A%d" % (r + 1)
    ws.auto_filter.ref = "A%d:%s%d" % (r, get_column_letter(len(header)), last)
    return ws, r


def tracker(path):
    wb = Workbook()
    wb.remove(wb.active)

    sheet(wb, "Студенты",
          ["ID", "Кто (имя или код)", "Вариант", "Платформа: проверка пройдена",
           "Дата старта", "Дата финиша", "Дошёл до урока", "Статус", "Комментарий"],
          [["S1", "", "A", "да / нет", "", "", "", "в процессе", ""],
           ["S2", "", "A", "да / нет", "", "", "", "в процессе", ""],
           ["S3", "", "A", "да / нет", "", "", "", "в процессе", ""]],
          [6, 22, 9, 16, 12, 12, 12, 14, 30],
          note="Одна строка — один участник. «Платформа: проверка пройдена» — результат "
               "предстартовой проверки из нулевого раздела: три запроса (прочитать, сохранить копию, "
               "добавить столбец).")

