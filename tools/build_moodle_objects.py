def parse_queries():
    """Все запросы З*.* из карточек уроков: id -> (текст, контроль). Таблицы бывают на 2 и 3 колонки."""
    out = {}
    for card in sorted((COURSE / "lessons").glob("*/card.md")):
        for line in card.read_text(encoding="utf-8").splitlines():
            s = line.strip()
            if not s.startswith("|"):
                continue
            cells = [c.strip() for c in s.strip("|").split("|")]
            if len(cells) < 2 or not re.fullmatch(r"З\d+\.\d+", cells[0]):
                continue
            qid, text = cells[0], cells[1]
            ctrl = cells[2] if len(cells) > 2 else ""
            if qid not in out and len(text) > 20:
                out[qid] = (text, ctrl)
    return out


def build_library(queries):
    rows = []
    for block, qid, name, check in LIBRARY:
        text, ctrl = queries.get(qid, ("—", "—"))
        rows.append([block, f"{qid} — {name}", text, check or ctrl,
                     "Имена клиентов и контакты, ключи и расшифровки кодов, пути к рабочим папкам, пароли"])
    buf = io.StringIO()
    w = csv.writer(buf, delimiter=",", lineterminator="\n", quoting=csv.QUOTE_ALL)
    w.writerow(["Категория", "Название", "Запрос", "Что проверять", "Что не класть"])
    w.writerows(rows)
    (OUT / "biblioteka-zaprosov.csv").write_text(buf.getvalue(), encoding="utf-8")

    body = "".join(
        f"<tr><td>{html.escape(r[0])}</td><td><b>{html.escape(r[1])}</b></td>"
        f"<td>{html.escape(r[2])}</td><td>{html.escape(r[3])}</td></tr>" for r in rows)
    (OUT / "biblioteka-zaprosov.html").write_text(
        "<h2>Библиотека запросов</h2>\n<p>Двенадцать запросов курса, по два на блок. "
        "Скопируйте нужную строку в поле «Запрос» своей записи.</p>\n"
        "<table><thead><tr><th>Категория</th><th>Название</th><th>Запрос</th>"
        "<th>Что проверять</th></tr></thead><tbody>" + body + "</tbody></table>\n"
        "<p><i>Не класть в библиотеку:</i> имена клиентов и контакты, ключи и расшифровки кодов, "
        "пути к рабочим папкам, пароли.</p>\n", encoding="utf-8")
    print("  biblioteka-zaprosov: %d запросов" % len(rows))
    return len(rows)


def build_glossary():
    buf = io.StringIO()
    w = csv.writer(buf, delimiter=",", lineterminator="\n", quoting=csv.QUOTE_ALL)
    w.writerow(["Концепция", "Определение"])
    w.writerows(GOOD for GOOD in GLOSSARY)
    (OUT / "glossarij.csv").write_text(buf.getvalue(), encoding="utf-8")
    print("  glossarij: %d терминов" % len(GLOSSARY))


def build_errors():
    rows_md = []
    for sym, cause, fix in ERRORS:
        rows_md.append(f"| {sym} | {cause} | {fix} |")
    md = ["# Карта типичных ошибок", "",
          "Симптом → причина → что делать. Одна и та же ошибка повторяется у разных людей; "
          "карта нужна, чтобы не искать причину с нуля.", "",
          "| Симптом | Причина | Что делать |", "|---|---|---|"] + rows_md + [""]
    (OUT / "karta-oshibok.md").write_text("\n".join(md), encoding="utf-8")

    body = "".join(f"<tr><td>{html.escape(s)}</td><td>{html.escape(c)}</td>"
                   f"<td>{html.escape(f)}</td></tr>" for s, c, f in ERRORS)
    (OUT / "karta-oshibok.html").write_text(
        "<h2>Карта типичных ошибок</h2>\n"
        "<p>Симптом → причина → что делать. Если ваша ошибка здесь есть, начинайте с последней "
        "колонки; если нет — сначала прочитайте сообщение агента.</p>\n"
        "<style>.eo{width:100%;border-collapse:collapse;font-size:13px}"
        ".eo th,.eo td{border:1px solid #e4e4e4;padding:8px 10px;text-align:left;vertical-align:top}"
        ".eo th{background:#f7f2ef}</style>\n"
        "<table class='eo'><thead><tr><th>Симптом</th><th>Причина</th><th>Что делать</th></tr>"
        "</thead><tbody>" + body + "</tbody></table>\n", encoding="utf-8")
    print("  karta-oshibok: %d ошибок" % len(ERRORS))


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    queries = parse_queries()
    print("запросов в карточках: %d" % len(queries))
    build_library(queries)
    build_glossary()
    build_errors()
    (OUT / "README.md").write_text(README, encoding="utf-8")
    for f in sorted(OUT.iterdir()):
        print("  %-28s %6.1f КБ" % (f.name, f.stat().st_size / 1024))
    print("объекты Moodle: %s" % OUT)


if __name__ == "__main__":
    main()
